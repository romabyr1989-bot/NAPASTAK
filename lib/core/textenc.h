/* Приведение текста к UTF-8.
 *
 * Данные приходят к нам файлами, которые готовили не мы: выгрузки из Excel и
 * из старых учётных систем в России — это, как правило, Windows-1251, иногда
 * CP866 (выгрузки из DOS-программ), реже KOI8-R. Если такой файл читать как
 * UTF-8, кириллица превращается в мусор вида «ЊЂ®б©б©», причём молча: ошибки
 * нет, данные просто испорчены и уезжают в хранилище в таком виде.
 *
 * Отдельная беда — метка порядка байтов (BOM). Excel ставит её в начало
 * UTF-8 файла, и первая колонка получает имя с невидимым префиксом: заголовок
 * выглядит как «id», а сравнение с «id» не срабатывает.
 */
#ifndef DFO_TEXTENC_H
#define DFO_TEXTENC_H

#include <stddef.h>
#include <stdbool.h>

/* Кодировки, которые умеем приводить к UTF-8. */
typedef enum {
    TEXTENC_UNKNOWN = 0,
    TEXTENC_UTF8,        /* в том числе с BOM */
    TEXTENC_UTF16LE,
    TEXTENC_UTF16BE,
    TEXTENC_CP1251,      /* Windows-1251 — русский Windows, выгрузки Excel */
    TEXTENC_CP866,       /* DOS-кириллица */
    TEXTENC_KOI8R
} TextEnc;

/* Имя кодировки для журнала и интерфейса. */
const char *textenc_name(TextEnc e);

/* Разбирает имя кодировки из настроек: "utf-8", "cp1251", "windows-1251",
 * "cp866", "koi8-r", "utf-16le", "utf-16be". Пустая строка и "auto" дают
 * TEXTENC_UNKNOWN — это указание определить кодировку самостоятельно. */
TextEnc textenc_parse(const char *name);

/* Определяет кодировку по содержимому.
 *
 * Порядок проверок: BOM (однозначен), затем корректность UTF-8 (её случайно
 * не получить — многобайтовые последовательности слишком специфичны), затем
 * однобайтовые кириллические — по тому, какая даёт более правдоподобный
 * русский текст. */
TextEnc textenc_detect(const char *data, size_t len);

/* Приводит к UTF-8. Возвращает свежий буфер (нулевой байт в конце) — его
 * освобождает вызывающий, — или NULL при нехватке памяти.
 *
 * enc == TEXTENC_UNKNOWN означает «определить самому». BOM снимается всегда.
 * Уже корректный UTF-8 копируется без изменений. Если определить не удалось,
 * данные копируются как есть: испортить их догадкой хуже, чем оставить.
 *
 * used, если не NULL, получает применённую кодировку — её стоит записать в
 * журнал, чтобы оператор видел, как именно был прочитан файл. */
char *textenc_to_utf8(const char *data, size_t len, TextEnc enc,
                      size_t *out_len, TextEnc *used);

/* Длина метки порядка байтов в начале данных (0, если её нет). */
size_t textenc_bom_len(const char *data, size_t len);

/* Корректен ли текст как UTF-8. */
bool textenc_is_utf8(const char *data, size_t len);

#endif /* DFO_TEXTENC_H */
